"""Why does kappa over-segment the semi-real logs?

Table 5 shows kappa producing 141 views for 4 hidden groups and 44 for 3, at a
purity of ~1.0: it never mixes groups, it only splits them.  The paper's scope
statement says kappa has no loop operator and unrolls repetition into
length-indexed views, so the natural hypothesis is that the extra views inside a
group differ mainly in how often something repeats -- i.e. in trace length.

This script rebuilds the enriched logs and measures, per hidden group:

  * how many kappa views it holds;
  * how many distinct trace lengths its traces have;
  * views per (group, length) cell -- if that is ~1, length explains the split;
  * how many views would remain if views were merged by their *activity set*
    (repetition ignored), which is an upper bound on what a loop operator could
    recover.

Writes ``results/diag_views.csv`` and LaTeX macros for the numbers Sect. 5.5
quotes.  Run after run_semireal.py; it repeats the same enrichment.
"""
from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import evaluation.run_semireal as SR  # noqa: E402
from tpv.log.enrich import split_and_enrich, variants_of  # noqa: E402
from tpv.views.views import induce_views  # noqa: E402

SHORT = {"hospital_billing": "HB", "road_traffic": "RT"}


def analyse(name: str, spec: dict, xes_dir: Path) -> "list[dict]":
    path = xes_dir / spec["xes"]
    cases, groups = SR.load_xes(path, spec["attribute"], spec.get("top_groups", 4))
    labels = sorted(set(groups.values()))
    by_group = {g: variants_of({c: s for c, s in cases.items() if groups[c] == g})
                for g in labels}
    models = {g: SR.mine(v) for g, v in by_group.items()}
    log, gt, _ = split_and_enrich(by_group,
                                  discover=lambda v, _g=iter(labels): models[next(_g)],
                                  name=f"{name}-diag")

    # trace -> view index, and trace -> its hidden group (via any of its cases)
    view_of = {t: i for i, v in enumerate(induce_views(log)) for t in v.traces}
    rows = []
    per_group_views = defaultdict(set)
    per_group_lengths = defaultdict(set)
    cell = defaultdict(set)                       # (group, length) -> views
    actset_views = defaultdict(set)               # group -> distinct activity sets
    for t, ids in log.case_ids.items():
        g = gt[str(ids[0])]
        per_group_views[g].add(view_of[t])
        per_group_lengths[g].add(len(t))
        cell[(g, len(t))].add(view_of[t])
        actset_views[g].add(frozenset(a for a, _ in t))
    for g in labels:
        cells = [len(v) for (gg, _), v in cell.items() if gg == g]
        rows.append({
            "log": name, "group": g,
            "views": len(per_group_views[g]),
            "lengths": len(per_group_lengths[g]),
            "views_per_length": round(sum(cells) / max(1, len(cells)), 2),
            "distinct_activity_sets": len(actset_views[g]),
        })
    return rows


def macros(df: pd.DataFrame) -> str:
    out = []
    for log, tag in SHORT.items():
        s = df[df.log == log]
        if s.empty:
            continue
        out.append(rf"\newcommand{{\diag{tag}ViewsPerLength}}{{{s.views_per_length.mean():.2f}}}")
        out.append(rf"\newcommand{{\diag{tag}Lengths}}{{{int(s.lengths.sum())}}}")
        out.append(rf"\newcommand{{\diag{tag}ActSets}}{{{int(s.distinct_activity_sets.sum())}}}")
    head = ("% AUTOGENERATED by evaluation/diag_views.py -- do not edit.\n")
    return head + "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--xes-dir", dest="xes_dir",
                    default=r"C:/Users/beyel/Documents/Code/cabumm/data")
    ap.add_argument("--out", default=str(ROOT / "evaluation" / "results"))
    ap.add_argument("--paper-out", dest="paper_out", default=None)
    a = ap.parse_args()
    rows = []
    for name, spec in SR.SEMIREAL_LOGS.items():
        if "xes" not in spec:
            continue
        print(f"=== {name}", flush=True)
        rows.extend(analyse(name, spec, Path(a.xes_dir)))
    df = pd.DataFrame(rows)
    out = Path(a.out)
    df.to_csv(out / "diag_views.csv", index=False)
    (out / "numbers_diag.tex").write_text(macros(df), encoding="utf-8")
    if a.paper_out:
        import shutil
        po = Path(a.paper_out)
        shutil.copyfile(out / "numbers_diag.tex", po / "numbers_diag.tex")
        print(f"synced macros to {po}")
    print(df.to_string(index=False))
    return 0


